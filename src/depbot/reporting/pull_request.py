"""PR delivery (owner: Member A, per docs/plan.md §9).

Every verified job gets a local PR artifact (``pr/pr-body.md`` + ``pr/pr.json``)
built only from recorded evidence. Publishing to GitHub is opt-in
(``create_pr``), runs only after the pre-PR policy gate, uses argv-only ``git``
and ``gh`` calls, never auto-merges, and is the only step that sees the
caller's GitHub credentials.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from collections.abc import Callable
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from depbot.models import UpgradePolicy
from depbot.policy.engine import PolicyDecision, pre_pr_gate
from depbot.state import DepBotState, JobStatus

PUBLISH_TIMEOUT_SECONDS = 120
_GITHUB_REMOTE = re.compile(r"github\.com[:/](?P<slug>[\w.-]+/[\w.-]+?)(?:\.git)?/?$")

Runner = Callable[..., subprocess.CompletedProcess]


class PullRequestDraft(BaseModel):
    model_config = ConfigDict(extra="forbid")

    title: str
    head_branch: str
    base_branch: str | None
    body_path: str
    verified: bool
    gate: PolicyDecision
    published: bool = False
    url: str | None = None
    publish_note: str = "local PR artifact only; not published to GitHub"
    labels: list[str] = Field(default_factory=lambda: ["depbot", "dependencies"])


def _fmt_cmd(args: list[str]) -> str:
    return " ".join(args).replace("|", "\\|")


def _local_roots(state: DepBotState) -> list[tuple[str, str]]:
    """Machine-specific prefixes to hide in the PR body, most specific first."""
    roots = [(state.worktree_path, "."), (state.artifacts_dir, "<artifacts>"),
             (os.environ.get("DEPBOT_CONAN_HOME"), "<conan-home>"), (os.environ.get("CONAN_HOME"), "<conan-home>"),
             (state.original_repo, "<repo>"), (os.getcwd(), "<depbot>"), (str(Path.home()), "~")]
    out: dict[str, str] = {}
    for raw, label in roots:
        if not raw or not os.path.isabs(raw) or raw == "/":
            continue
        for variant in {raw.rstrip("/"), str(Path(raw).resolve()).rstrip("/")}:
            out.setdefault(variant, label)
    return sorted(out.items(), key=lambda item: -len(item[0]))


_ABS_TAIL = re.compile(r"(?<![\w.~<>:/-])/(?:[\w.+@-]+/)*[\w.+@-]+")


def redact_local_paths(text: str, state: DepBotState) -> str:
    """Replace local absolute paths (worktree, artifacts, Conan home, home dir) with
    stable placeholders so a published PR never reveals the runner's filesystem."""
    for prefix, label in _local_roots(state):
        text = text.replace(f"file://{prefix}/", f"{label}/" if label != "." else "")
        text = text.replace(f"file://{prefix}", label)
        text = re.sub(re.escape(prefix) + r"(?=/|\b|$)", label, text)
    # Anything still absolute and outside the known roots (e.g. /tmp scratch dirs) keeps
    # only its last two components.
    return _ABS_TAIL.sub(lambda m: "…/" + "/".join(m.group(0).split("/")[-2:]) if m.group(0).count("/") > 2
                         else m.group(0), text)


def build_pr_body(state: DepBotState, gate: PolicyDecision, *, published: bool) -> str:
    dep = state.dependency
    v = state.verification
    lines = [
        f"## Upgrade `{dep.name}` {dep.current_version} → {dep.target_version}",
        "",
    ]
    if not published:
        lines += ["> **Local PR artifact** generated by DepBot. It has not been published to GitHub.", ""]
    verified = state.status in (JobStatus.VERIFIED, JobStatus.PR_CREATED)
    lines += [
        f"- Verification: **{'passed' if verified else 'NOT verified'}** (status `{state.status.value}`)",
        f"- Package manager: `{dep.package_manager.value}` (`{dep.manifest_path}`)",
        f"- Run: `{state.run_id}`",
        f"- Repair attempts: {state.repair_attempts}/{state.max_repair_attempts}",
        "",
        "### Breaking changes (from upstream evidence)",
        "",
    ]
    if state.breaking_changes:
        for c in state.breaking_changes:
            urls = ", ".join(c.evidence_urls) or "no evidence URL"
            lines.append(f"- **{c.id}** {c.title} ({c.change_type.value}, confidence {c.confidence:.2f}) — {urls}")
            if c.evidence_excerpt:
                lines.append(f"  > {c.evidence_excerpt.strip()[:300]}")
    else:
        lines.append("- none recorded")
    lines += ["", "### Affected usages", ""]
    if state.usages:
        for u in state.usages:
            lines.append(
                f"- `{u.file_path}:{u.line_start}` `{u.symbol}` — {u.impact.value} "
                f"({u.analysis_method.value}, cites {', '.join(u.related_change_ids)})"
            )
    else:
        lines.append("- none found")
    lines += ["", "### Files changed", ""]
    lines += [f"- `{f}`" for f in state.changed_files] or ["- none"]
    lines += [
        "",
        "### Commands executed",
        "",
        "| Step | Command | Exit | Duration |",
        "|---|---|---:|---:|",
    ]
    for c in state.command_results:
        exit_text = "timeout" if c.timed_out else str(c.exit_code)
        lines.append(f"| {c.command_label} | `{_fmt_cmd(c.args)}` | {exit_text} | {c.duration_seconds:.1f}s |")
    if v is not None:
        lines += [
            "",
            f"Tests: {v.tests_passed if v.tests_passed is not None else '?'} passed, "
            f"{v.tests_failed if v.tests_failed is not None else '?'} failed.",
        ]
    lines += [
        "",
        "### Policy",
        "",
        *[f"- {r}" for r in gate.reasons],
        "",
        "### Limitations",
        "",
        "- Impact analysis is text-based unless a usage says `clang_ast`.",
        "- Only the requested direct dependency was changed; transitive resolution is not upgraded.",
        "- This PR must be reviewed and merged by a human.",
        "",
    ]
    return redact_local_paths("\n".join(lines), state)


def prepare_pull_request(
    state: DepBotState, policy: UpgradePolicy, artifacts_dir: Path, *, base_branch: str | None
) -> PullRequestDraft | None:
    """Write the local PR artifact if the pre-PR gate allows; return None otherwise."""
    v = state.verification
    gate = pre_pr_gate(policy, verification_passed=bool(v and v.passed), tests_ran=bool(v and v.tests))
    if not gate.allowed:
        return None
    pr_dir = artifacts_dir / "pr"
    pr_dir.mkdir(parents=True, exist_ok=True)
    body_path = pr_dir / "pr-body.md"
    body_path.write_text(build_pr_body(state, gate, published=False), encoding="utf-8")
    draft = PullRequestDraft(
        title=f"depbot: upgrade {state.dependency.name} to {state.dependency.target_version}",
        head_branch=state.working_branch,
        base_branch=base_branch,
        body_path=str(body_path),
        verified=bool(v and v.passed),
        gate=gate,
    )
    _save(draft, pr_dir)
    return draft


def _save(draft: PullRequestDraft, pr_dir: Path) -> None:
    (pr_dir / "pr.json").write_text(draft.model_dump_json(indent=2) + "\n", encoding="utf-8")


def _call(run: Runner, args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return run(args, cwd=cwd, capture_output=True, text=True, timeout=PUBLISH_TIMEOUT_SECONDS,
               check=False, shell=False)


def publish_pull_request(
    draft: PullRequestDraft, state: DepBotState, *, run: Runner = subprocess.run
) -> PullRequestDraft:
    """Push the working branch to the source repo's GitHub origin and open a PR."""
    source, worktree = Path(state.original_repo), Path(state.worktree_path)

    def done(note: str, **update) -> PullRequestDraft:
        result = draft.model_copy(update={"publish_note": note, **update})
        _save(result, Path(draft.body_path).parent)
        return result

    remote = _call(run, ["git", "remote", "get-url", "origin"], source)
    match = _GITHUB_REMOTE.search(remote.stdout.strip()) if remote.returncode == 0 else None
    if match is None:
        return done("source repository has no GitHub 'origin' remote; local PR artifact only")
    if not draft.base_branch:
        return done("no base branch known for this repository; local PR artifact only")
    push = _call(run, ["git", "push", remote.stdout.strip(), f"HEAD:refs/heads/{draft.head_branch}"], worktree)
    if push.returncode != 0:
        return done(f"git push failed: {push.stderr.strip()[:300]}")
    Path(draft.body_path).write_text(build_pr_body(state, draft.gate, published=True), encoding="utf-8")
    # REST (`POST /repos/{owner}/{repo}/pulls`) via `gh api`: works wherever `gh` is authenticated,
    # including environments where GitHub's GraphQL API (used by `gh pr create`) is unavailable.
    create = _call(
        run,
        ["gh", "api", "--method", "POST", f"repos/{match['slug']}/pulls",
         "-f", f"title={draft.title}", "-f", f"head={draft.head_branch}", "-f", f"base={draft.base_branch}",
         "-F", f"body=@{draft.body_path}", "--jq", ".html_url"],
        worktree,
    )
    if create.returncode != 0:
        return done(f"PR creation failed: {(create.stderr or create.stdout).strip()[:300]}")
    url = create.stdout.strip().splitlines()[-1] if create.stdout.strip() else None
    if not url or not url.startswith("https://"):
        return done(f"PR creation returned no URL: {create.stdout.strip()[:200]}")
    return done("published (auto-merge disabled)", published=True, url=url)


def load_draft(pr_dir: Path) -> PullRequestDraft:
    return PullRequestDraft.model_validate(json.loads((pr_dir / "pr.json").read_text(encoding="utf-8")))
